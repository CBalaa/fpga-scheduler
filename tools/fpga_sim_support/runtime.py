"""Local-only application construction; production has no simulator registration."""
from dataclasses import replace
from pathlib import Path
from unittest.mock import patch

from fpga_scheduler.config import load
from fpga_scheduler.service import Application

from .board import ResidentSimulator
from .scenarios import check_state_directory


def load_local_config(directory):
    root = Path(directory).resolve()
    config = load(root / 'config.local.toml')
    state = root / 'state'
    expected = dict(hardware_project=str(state / 'sim/project'), lock_dir=str(state / 'sim/locks'))
    if (config.backend != 'bosc-resident' or config.state_dir != state or
            config.token_file != root / 'service.token' or config.bind != '127.0.0.1' or
            len(config.nodes) != 1 or
            any(config.resident.get(key) != value for key, value in expected.items()) or
            config.nodes[0].uvhs_shell != str(state / 'sim/uvhs-sim') or
            config.nodes[0].uart_prefix != str(state / 'sim/uart')):
        raise ValueError('Use the isolated localhost config generated by tools/fpga_sim.py init')
    check_state_directory(config.state_dir)
    return config


def create_application(directory, *, port=None):
    config = load_local_config(directory)
    if port is not None:
        config = replace(config, port=port)

    def virtual_backend(nodes, state_dir, **options):
        # Replace only hardware construction during this local harness startup.
        # The actual Application, queue, API, Resident and Session remain in use.
        options.pop('hardware_project')
        options.pop('lock_dir')
        return ResidentSimulator(nodes, state_dir, **options)

    with patch('fpga_scheduler.backends.resident.Resident', new=virtual_backend):
        return Application(config)
